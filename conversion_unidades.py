kilometros = float(input("Distancia en kilometros: "))

metros = kilometros * 1000
centimetros = kilometros * 100000
millas = kilometros * 0.621371

print("=========================")
print("     CONVERSION DE UNIDADES")
print("=========================")
print("Kilometros:", kilometros)
print("Metros:", metros)
print("Centimetros:", centimetros)
print("Millas:", millas)