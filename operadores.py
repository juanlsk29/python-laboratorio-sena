a = 10
b = 3

print(a + b) #Suma el valor de ambos operandos.
print(a - b) #Resta el segundo operando del primero.
print(a * b) #Multiplica ambos valores.
print(a / b) #Divide el primer número entre el segundo obteniendo un resultado con decimales.
print(a // b)#Divide ambos números y descarta los decimales quedándose solo con la parte entera.
print(a % b) #Calcula el sobrante o residuo que queda tras una división entera.
print(a ** b)#Eleva el primer número a la potencia del segundo número.

total_minutos = 135

horas = total_minutos // 60
minutos = total_minutos % 60

print("Horas:", horas)
print("Minutos restantes:", minutos)
